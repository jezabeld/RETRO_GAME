/**
 * @brief Lee el registro de estado de la EEPROM
 * @retval Valor del registro de estado
 */
uint8_t EEPROM_ReadStatus(void)
{
    uint8_t cmd = EEPROM_CMD_RDSR;
    uint8_t status = 0;

    EEPROM_CS_LOW();
    HAL_SPI_Transmit(&hspi2, &cmd, 1, SPI_TIMEOUT);
    HAL_SPI_Receive(&hspi2, &status, 1, SPI_TIMEOUT);
    EEPROM_CS_HIGH();

    return status;
}

/**
 * @brief Habilita la escritura en la EEPROM
 */
void EEPROM_WriteEnable(void)
{
    uint8_t cmd = EEPROM_CMD_WREN;

    EEPROM_CS_LOW();
    HAL_SPI_Transmit(&hspi2, &cmd, 1, SPI_TIMEOUT);
    EEPROM_CS_HIGH();
}

/**
 * @brief Escribe un byte en la EEPROM
 * @param address Dirección de memoria (0x0000 a 0x7FFF)
 * @param data Dato a escribir
 */
void EEPROM_WriteByte(uint16_t address, uint8_t data)
{
    uint8_t buffer[4];

    // Habilitar escritura
    EEPROM_WriteEnable();

    // Preparar comando y dirección
    buffer[0] = EEPROM_CMD_WRITE;
    buffer[1] = (address >> 8) & 0xFF;  // Dirección alta
    buffer[2] = address & 0xFF;         // Dirección baja
    buffer[3] = data;

    EEPROM_CS_LOW();
    HAL_SPI_Transmit(&hspi2, buffer, 4, SPI_TIMEOUT);
    EEPROM_CS_HIGH();

    // Esperar a que termine la escritura (bit WIP = 0)
    HAL_Delay(5);
    while(EEPROM_ReadStatus() & 0x01);
}

/**
 * @brief Lee un byte de la EEPROM
 * @param address Dirección de memoria (0x0000 a 0x7FFF)
 * @retval Dato leído
 */
uint8_t EEPROM_ReadByte(uint16_t address)
{
    uint8_t buffer[3];
    uint8_t data = 0;

    // Preparar comando y dirección
    buffer[0] = EEPROM_CMD_READ;
    buffer[1] = (address >> 8) & 0xFF;  // Dirección alta
    buffer[2] = address & 0xFF;         // Dirección baja

    EEPROM_CS_LOW();
    HAL_SPI_Transmit(&hspi2, buffer, 3, SPI_TIMEOUT);
    HAL_SPI_Receive(&hspi2, &data, 1, SPI_TIMEOUT);
    EEPROM_CS_HIGH();

    return data;
}

